const byKey = new Map(LEGAL_SOURCES.map((s) => [s.key, s]));

export function getSource(key: string): LegalSource {
    const s = byKey.get(key);
    if (!s) throw new Error(`Unknown legal source key: ${key}`);
    return s;
}

export function hasSource(key: string): boolean {
    return byKey.has(key);
}

/** The version of a source family in force on a given date, or null. */
export function applicableSource(key: string, eventDate: string): LegalSource | null {
    const s = byKey.get(key);
    if (!s) return null;
    if (eventDate < s.effectiveFrom) return null;
    if (s.effectiveTo && eventDate > s.effectiveTo) return null;
    return s;
}

export function citeSource(key: string): { key: string; title: string; reference: string; url: string; version: string } {
    const s = getSource(key);
    return { key: s.key, title: s.title, reference: s.reference, url: s.url, version: s.version };
}
