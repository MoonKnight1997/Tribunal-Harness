/**
 * Legal source registry.
 *
 * Every legal rule the product applies, and every source a generated document
 * cites, is registered here — separately from model prompts. The registry is
 * versioned in git; changing a source is a reviewed code change.
 *
 * Hierarchy (highest authority first):
 *   1. legislation.gov.uk   2. GOV.UK   3. Acas   4. HMCTS / tribunal procedure
 *   5. curated case law      6. secondary (only where explicitly labelled)
 *
 * The registry distinguishes the NEWEST source from the source LEGALLY
 * APPLICABLE to the user's event: `applicableSources(key, eventDate)` picks the
 * version whose [effectiveFrom, effectiveTo] window contains the event date.
 */

